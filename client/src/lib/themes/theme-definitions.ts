// Helper functions
export const getThemeById = (id: string): KeyboardTheme | undefined => {
  return allThemes.find(theme => theme.id === id);
};

export const getThemesByRarity = (rarity: KeyboardTheme['rarity']): KeyboardTheme[] => {
  return allThemes.filter(theme => theme.rarity === rarity);
};

export const getThemesByTier = (tier: KeyboardTheme['unlockTier']): KeyboardTheme[] => {
  return allThemes.filter(theme => theme.unlockTier === tier);
};

export const getUnlockedThemes = (unlockedIds: string[]): KeyboardTheme[] => {
  return allThemes.filter(theme => unlockedIds.includes(theme.id) || theme.isUnlocked);
};

export const getCompatibleThemes = (layout: string): KeyboardTheme[] => {
  return allThemes.filter(theme => 
    theme.compatibleLayouts.includes('universal') || 
    theme.compatibleLayouts.includes(layout as any)
  );
};